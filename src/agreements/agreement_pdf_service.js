const PDFDocument = require("pdfkit");

function safe_filename_part(value) {
  return String(value || "agreement")
    .replace(/[^a-z0-9-_]+/gi, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function stream_agreement_pdf(res, agreement) {
  const filename = [
    "tenancy-agreement",
    safe_filename_part(agreement.tenant_name),
    agreement.id,
  ].join("-");

  const document = new PDFDocument({
    size: "A4",
    margin: 52,
    info: {
      Title: `Tenancy Agreement - ${agreement.tenant_name}`,
      Author: "Rental Management System",
    },
  });

  res.status(200);
  res.setHeader(
    "Content-Type",
    "application/pdf"
  );

  res.setHeader(
    "Content-Disposition",
    `attachment; filename="${filename}.pdf"`
  );

  document.pipe(res);

  document
    .font("Helvetica-Bold")
    .fontSize(16)
    .text("TENANCY AGREEMENT", {
      align: "center",
    });

  document.moveDown(1.5);

  document
    .font("Helvetica")
    .fontSize(10.5)
    .text(agreement.rendered_content, {
      lineGap: 5,
      align: "left",
    });

  document.moveDown(2);

  document
    .fontSize(8)
    .fillColor("#666666")
    .text(
      `Generated by Rental Management System on ${new Date(
        agreement.generated_at
      ).toLocaleDateString("en-KE")}.`,
      {
        align: "center",
      }
    );

  document.end();
}

module.exports = {
  stream_agreement_pdf,
};